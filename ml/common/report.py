"""Render MODEL_CARD.md from metrics.json (Ticket R10.1).

Enforces Rule T4 (Reports are generated) and fails strictly on missing values.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

REQUIRED_CARD_FIELDS = [
    "model_name",
    "version",
    "task",
    "dataset",
    "n_train",
    "n_test",
    "metrics",
    "generated_by",
    "git_sha",
    "provenance",
]


def render_model_card(metrics_data: dict[str, Any] | Path | str, output_path: Path | str | None = None) -> str:
    """Render a MODEL_CARD.md string from metrics dictionary or path.

    Fails strictly with ValueError if any required field is missing (Rule T4).
    """
    if isinstance(metrics_data, (Path, str)):
        p = Path(metrics_data)
        if not p.exists():
            raise FileNotFoundError(f"metrics.json not found: {p}")
        with p.open("r", encoding="utf-8") as f:
            data = json.load(f)
    elif isinstance(metrics_data, dict):
        data = metrics_data
    else:
        raise TypeError(f"Invalid type for metrics_data: {type(metrics_data)}")

    # Strict check: fail on missing or empty required fields
    missing_fields = []
    for field in REQUIRED_CARD_FIELDS:
        if field not in data or data[field] is None:
            missing_fields.append(field)

    if missing_fields:
        raise ValueError(f"Missing required field(s) in metrics for model card: {', '.join(missing_fields)}")

    model_name = data["model_name"]
    version = data["version"]
    task = data["task"]
    dataset_info = data["dataset"]
    n_train = data["n_train"]
    n_test = data["n_test"]
    metrics = data["metrics"]
    baseline = data.get("baseline_comparison", {})
    limitations = data.get("limitations", ["None recorded"])
    generated_by = data["generated_by"]
    git_sha = data["git_sha"]
    prov = data["provenance"]

    lines = [
        f"# Model Card: {model_name}",
        "",
        f"- **Version**: `{version}`",
        f"- **Task**: {task}",
        f"- **Provenance**: `{prov}`",
        f"- **Generated by**: `{generated_by}`",
        f"- **Git SHA**: `{git_sha}`",
        "",
        "## Dataset Details",
        "",
    ]

    if isinstance(dataset_info, dict):
        for k, v in sorted(dataset_info.items()):
            lines.append(f"- **{k.title()}**: {v}")
    else:
        lines.append(f"- **Dataset**: {dataset_info}")

    lines.extend([
        f"- **Training Set Size (n_train)**: {n_train}",
        f"- **Test Set Size (n_test)**: {n_test}",
        "",
        "## Performance Metrics",
        "",
        "| Metric | Measured Value |",
        "|---|---|",
    ])

    if isinstance(metrics, dict):
        for m_name, m_val in sorted(metrics.items()):
            if isinstance(m_val, float):
                val_str = f"{m_val:.4f}"
            else:
                val_str = str(m_val)
            lines.append(f"| {m_name} | {val_str} |")
    else:
        lines.append(f"| Value | {metrics} |")

    if baseline:
        lines.extend([
            "",
            "## Baseline Comparison",
            "",
            "| Metric | Baseline | Model | Delta | CI (95%) | p-value |",
            "|---|---|---|---|---|---|",
        ])
        if isinstance(baseline, dict):
            for k, b_info in sorted(baseline.items()):
                if isinstance(b_info, dict):
                    b_val = b_info.get("baseline", "N/A")
                    m_val = b_info.get("model", "N/A")
                    delta = b_info.get("delta", "N/A")
                    ci_str = f"[{b_info.get('ci_lower', '')}, {b_info.get('ci_upper', '')}]" if "ci_lower" in b_info else "N/A"
                    p_val = b_info.get("p_value", "N/A")
                    lines.append(f"| {k} | {b_val} | {m_val} | {delta} | {ci_str} | {p_val} |")

    lines.extend([
        "",
        "## Limitations & Known Weaknesses",
        "",
    ])
    if isinstance(limitations, list):
        for lim in limitations:
            lines.append(f"- {lim}")
    else:
        lines.append(f"- {limitations}")

    lines.append("")
    rendered_md = "\n".join(lines)

    if output_path is not None:
        out_p = Path(output_path)
        out_p.parent.mkdir(parents=True, exist_ok=True)
        out_p.write_text(rendered_md, encoding="utf-8")

    return rendered_md
